#!/usr/bin/env python3
"""Generate Localizable.xcstrings, InfoPlist.xcstrings and functions/src/i18n.data.ts
from tools/i18n/<lang>.json. Source language: zh-Hans. Run: python3 tools/i18n/build.py"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
LANGS = ["zh-Hans","en","zh-Hant","ja","ko","es","fr","de","pt-BR","it","ru","th","vi","id","tr","ar"]
data = {l: json.load(open(os.path.join(HERE, f"{l}.json"), encoding="utf-8")) for l in LANGS}
src = data["zh-Hans"]
for l in LANGS: assert set(data[l]) == set(src), (l, set(data[l]) ^ set(src))

def catalog(keys, strip=""):
    s = {}
    for k in sorted(keys):
        s[k[len(strip):]] = {"extractionState": "manual", "localizations": {
            l: {"stringUnit": {"state": "translated", "value": data[l][k]}} for l in LANGS}}
    return {"sourceLanguage": "zh-Hans", "strings": s, "version": "1.0"}

def dump(path, obj):
    with open(os.path.join(ROOT, path), "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=2, sort_keys=True); f.write("\n")

dump("DriftBottle/Resources/Localizable.xcstrings", catalog([k for k in src if not k.startswith(("plist.","srv."))]))
dump("DriftBottle/Resources/InfoPlist.xcstrings", catalog([k for k in src if k.startswith("plist.")], "plist."))
SHARED = ["ai.first_visitor","ai.name","nickname.format","onb.age_min","home.too_frequent","chat.image"]
srv = {l: {**{k[4:]: v for k, v in data[l].items() if k.startswith("srv.")}, **{k: data[l][k] for k in SHARED}} for l in LANGS}
with open(os.path.join(ROOT, "functions/src/i18n.data.ts"), "w", encoding="utf-8") as f:
    f.write("// GENERATED by tools/i18n/build.py — do not edit.\n")
    f.write("export const LANGS = " + json.dumps(LANGS) + " as const;\n")
    f.write("export const STRINGS: Record<string, Record<string, string>> = " + json.dumps(srv, ensure_ascii=False, indent=1) + ";\n")
print("ok", len(src), "keys")
